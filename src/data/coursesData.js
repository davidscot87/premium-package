export const getCoursesByType = (type) => {
  const allCourses = getAllCourses()
  return allCourses.filter(course => course.type === type)
}

export const getCourseById = (id) => {
  const allCourses = getAllCourses()
  return allCourses.find(course => course.id === id)
}
